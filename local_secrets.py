"""Windows DPAPI protection for local, reversible secret sidecars."""

from __future__ import annotations

import ctypes
import json
import os
from ctypes import wintypes
from pathlib import Path
from typing import Any


MAGIC = b"MDTK-SECRETS\x01"
CRYPTPROTECT_UI_FORBIDDEN = 0x01


class _DataBlob(ctypes.Structure):
    _fields_ = [
        ("cbData", wintypes.DWORD),
        ("pbData", ctypes.POINTER(ctypes.c_ubyte)),
    ]


def secrets_path_for(markdown_path: Path) -> Path:
    return markdown_path.with_suffix(".secrets")


def _crypt(data: bytes, *, decrypt: bool) -> bytes:
    if os.name != "nt":
        raise OSError("El archivo .secrets requiere Windows y la misma cuenta de usuario.")
    if not data:
        raise ValueError("no se puede cifrar un archivo vacío")

    source_buffer = (ctypes.c_ubyte * len(data)).from_buffer_copy(data)
    source = _DataBlob(len(data), source_buffer)
    destination = _DataBlob()
    crypt32 = ctypes.WinDLL("crypt32", use_last_error=True)
    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    function = crypt32.CryptUnprotectData if decrypt else crypt32.CryptProtectData
    description_type = ctypes.POINTER(wintypes.LPWSTR) if decrypt else wintypes.LPCWSTR
    function.argtypes = [
        ctypes.POINTER(_DataBlob),
        description_type,
        ctypes.c_void_p,
        ctypes.c_void_p,
        ctypes.c_void_p,
        wintypes.DWORD,
        ctypes.POINTER(_DataBlob),
    ]
    function.restype = wintypes.BOOL
    kernel32.LocalFree.argtypes = [ctypes.c_void_p]
    kernel32.LocalFree.restype = ctypes.c_void_p

    description = wintypes.LPWSTR() if decrypt else "MD Toolkit local secrets"
    description_argument = ctypes.byref(description) if decrypt else description
    if not function(
        ctypes.byref(source),
        description_argument,
        None,
        None,
        None,
        CRYPTPROTECT_UI_FORBIDDEN,
        ctypes.byref(destination),
    ):
        raise ctypes.WinError(ctypes.get_last_error())
    try:
        return ctypes.string_at(destination.pbData, destination.cbData)
    finally:
        kernel32.LocalFree(destination.pbData)
        if decrypt and description:
            kernel32.LocalFree(description)


def save_secrets(path: Path, payload: dict[str, Any]) -> None:
    """Write an encrypted sidecar readable only by this Windows user."""
    serialized = json.dumps(payload, ensure_ascii=True, separators=(",", ":")).encode("utf-8")
    encrypted = MAGIC + _crypt(serialized, decrypt=False)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_bytes(encrypted)
    temporary.replace(path)


def load_secrets(path: Path) -> dict[str, Any]:
    """Decrypt and validate a sidecar generated by this application."""
    encrypted = path.read_bytes()
    if not encrypted.startswith(MAGIC):
        raise ValueError(f"el archivo no es un vault de MD Toolkit: {path}")
    try:
        payload = json.loads(_crypt(encrypted[len(MAGIC) :], decrypt=True).decode("utf-8"))
    except (UnicodeError, json.JSONDecodeError) as error:
        raise ValueError(f"el vault está dañado o no pertenece a este usuario: {path}") from error
    if not isinstance(payload, dict) or payload.get("version") != 1:
        raise ValueError("versión de vault no compatible")
    return payload
